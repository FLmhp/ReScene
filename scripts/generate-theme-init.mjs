import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";

const source = readFileSync(new URL("../packages/design-tokens/src/tokens.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
}).outputText;
const output = `/* Generated by scripts/generate-theme-init.mjs; do not edit. */
(function(exports) {
${compiled}
  var root = document.documentElement;
  var query = new URLSearchParams(location.search).get("theme");
  var storedTheme = null, storedDisplay = null, legacyColorway = null;
  try { storedTheme = localStorage.getItem(exports.THEME_STORAGE_KEY); } catch (error) {}
  try { storedDisplay = localStorage.getItem(exports.DISPLAY_STORAGE_KEY); } catch (error) {}
  try { legacyColorway = localStorage.getItem(exports.COLORWAY_STORAGE_KEY); } catch (error) {}
  var preference = query === "light" || query === "dark" ? query : exports.themePreference(storedTheme);
  var media = typeof matchMedia === "function" ? matchMedia("(prefers-color-scheme: dark)") : null;
  root.dataset.themePreference = preference;
  exports.applyDisplayToRoot(root, preference === "dark" || (preference === "system" && !!media && media.matches),
    exports.displayPreferences(storedDisplay, legacyColorway));
  if (media) {
    var update = function(event) {
      if (root.dataset.themePreference !== "system") return;
      exports.applyDisplayToRoot(root, event.matches, exports.displayPreferences({
        colorway: root.dataset.colorway, primary: root.dataset.primary,
        fontSize: root.dataset.fontSize, surface: root.dataset.surface
      }));
    };
    if (media.addEventListener) media.addEventListener("change", update);
    else if (media.addListener) media.addListener(update);
  }
})({});
`;
const files = ["../apps/web/public/theme-init.js", "../apps/desktop/public/theme-init.js"];
let stale = false;
for (const file of files) {
  const path = new URL(file, import.meta.url);
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(path, "utf8"); } catch {}
    if (current !== output) { console.error(`${file} is out of date`); stale = true; }
  } else {
    writeFileSync(path, output);
  }
}
if (stale) process.exitCode = 1;
